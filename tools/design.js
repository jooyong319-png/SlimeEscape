const pick = process.argv[2] ? Number(process.argv[2]) - 1 : -1;

CASES.forEach((c, i) => {
  console.log('='.repeat(72));
  console.log((i + 1) + '. [' + c.id + '] ' + c.name);

  const k = check(c.grid);
  console.log('   조각 ' + k.foods + ' · 목표 ' + k.target + '칸' + (k.zone ? ' · 무중력 ' + k.zone + '칸' : ''));
  if (pick < 0) c.grid.forEach(r => console.log('   ' + r));
  if (!k.ok) { k.errors.forEach(m => console.log('   X ' + m)); return; }

  let r;
  try { r = E.solve({ grid: c.grid, gravity: true }); }
  catch (e) { console.log('   X ' + e.message); return; }
  if (!r.ok) { console.log('   X ' + r.why + (r.states ? ' (탐색 ' + r.states.toLocaleString() + ')' : '')); return; }

  const a = analyze({ grid: c.grid, gravity: true });
  console.log('   ' + (r.shortest === 1 ? 'OK' : '~ ') + ' ' + r.moves + '걸음 · 최단해 ' + r.shortest + '개 · ' +
    '이미 진 상태 ' + (a ? (a.lost * 100).toFixed(1) + '%' : '(생략)') +
    (a ? ' · 진 뒤 ' + a.wander + '걸음 헤맴' + (a.wander > 14 ? ' 🔴' : '') : ''));
  console.log('   ' + r.path);

  if (pick === i) {
    const t = E.trace({ grid: c.grid, gravity: true });
    t.steps.forEach((s, n) => {
      console.log('\n   ' + (n === 0 ? '시작' : s.sym) + '  길이 ' + s.st.body.length);
      E.render(t.L, s.st).forEach(row => console.log('   ' + row));
    });
  }
});
